    public static string ToText(AssetLimitsDef l)
    {
        var sb = new StringBuilder("ТРЕБОВАНИЯ К РЕСУРСАМ\n\n");
        foreach (var sec in Build(l))
        {
            sb.AppendLine(sec.Title.ToUpperInvariant());
            foreach (var line in sec.Lines) sb.AppendLine("  • " + line);
            if (sec.Table != null)
                foreach (var row in sec.Table)
                    sb.AppendLine("  " + string.Join(" | ", row));
            sb.AppendLine();
        }
        return sb.ToString();
    }

    public static string ToHtml(AssetLimitsDef l)
    {
        string E(string s) => WebUtility.HtmlEncode(s);
        var sb = new StringBuilder();
        sb.Append("<!doctype html><html lang=\"ru\"><head><meta charset=\"utf-8\"><title>Требования к ресурсам</title>");
        sb.Append("<style>body{font-family:sans-serif;max-width:60em;margin:2em auto;padding:0 1em;line-height:1.45}table{border-collapse:collapse}td,th{border:1px solid #999;padding:.3em .6em;text-align:left}h2{margin-top:1.6em}</style></head><body>");
        sb.Append("<h1>Требования к ресурсам</h1>");
        foreach (var sec in Build(l))
        {
            sb.Append($"<h2>{E(sec.Title)}</h2><ul>");
            foreach (var line in sec.Lines) sb.Append($"<li>{E(line)}</li>");
            sb.Append("</ul>");
            if (sec.Table != null)
            {
                sb.Append("<table>");
                for (int i = 0; i < sec.Table.Count; i++)
                {
                    sb.Append("<tr>");
                    foreach (var c in sec.Table[i]) sb.Append(i == 0 ? $"<th>{E(c)}</th>" : $"<td>{E(c)}</td>");
                    sb.Append("</tr>");
                }
                sb.Append("</table>");
            }
        }
        sb.Append("</body></html>");
        return sb.ToString();
    }
